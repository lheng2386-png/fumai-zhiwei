/* Run against a local demo server with a disposable SQLite DB; no model key required. */
const {chromium}=require(process.env.FUMAI_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=process.env.FUMAI_CHECK_URL||'http://127.0.0.1:4196';
const output=process.env.FUMAI_TEST_OUTPUT||path.resolve('outputs');
fs.mkdirSync(output,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.FUMAI_BROWSER_EXECUTABLE?{executablePath:process.env.FUMAI_BROWSER_EXECUTABLE}:{})});
 const context=await browser.newContext({viewport:{width:1440,height:900},reducedMotion:'reduce'});
 const page=await context.newPage(),errors=[],checks=[];
 for(const p of [page])p.on('pageerror',e=>errors.push(e.message));
 const headers=async p=>p.evaluate(()=>({'Content-Type':'application/json','X-Fumai-Client':localStorage.getItem('fumai-agent-client'),'X-Fumai-Session':sessionStorage.getItem('fumai-agent-session')}));
 const ask=async(p,question)=>{
  const count=await p.locator('#agent-workbench .agent-message.assistant').count();
  const result=p.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/agent-api/analysis-tasks'));
  await p.locator('#workbench-question').fill(question);await p.locator('#agent-workbench .agent-send').click();
  const task=await (await result).json();
  await p.waitForFunction(n=>document.querySelectorAll('#agent-workbench .agent-message.assistant').length>n,count);
  await p.waitForFunction(()=>!document.querySelector('#workbench-question').disabled);
  if(task.result)return task.result;
  const stored=await p.request.get(base+'/agent-api/analysis-tasks/'+task.task_id,{headers:await headers(p)});
  assert.equal(stored.status(),200);return (await stored.json()).result;
 };
 const visible=async(p,label)=>{
  const box=await p.locator('#agent-workbench .agent-input-area').boundingBox();
  assert.ok(box&&box.y>=0&&box.y+box.height<=p.viewportSize().height+1,label);
  assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),label+' overflow');
 };
 try{
  await page.goto(base+'/#agent',{waitUntil:'networkidle'});
  const original=await page.evaluate(()=>({client:localStorage.getItem('fumai-agent-client'),session:sessionStorage.getItem('fumai-agent-session')}));
  assert.ok(original.client&&original.session);
  const first=await ask(page,'分析 inv_07 的异常证据');
  assert.equal(first.response_type,'analysis');assert.ok(first.events.length);
  assert.equal(await page.locator('.agent-model-text').count(),0);
  assert.equal(await page.getByRole('heading',{name:'建议核查路径',exact:true}).count(),1);
  checks.push('one report, one checklist, observed evidence and unranked hypotheses');
  const follow=await ask(page,'为什么这样判断？');
  assert.equal(follow.intent,'followup');assert.deepEqual(follow.source_run_ids,[first.run_id]);
  assert.equal(await page.locator('.agent-message.assistant').last().locator('.agent-evidence-card').count(),0);
  assert.equal(await page.locator('.agent-message.assistant').last().locator('.agent-question-answer').count(),1);
  checks.push('followup reuses stored evidence and renders concise answer');
  const history=await ask(page,'列出之前的设备分析记录');
  assert.equal(history.intent,'history');assert.equal(history.model_status,'not_invoked');assert.equal(history.history_records.length,1);
  checks.push('natural-language history does not reanalyze');
  const correction=await ask(page,'不对，通信异常没有证据，不应该排第一');
  assert.equal(correction.intent,'correction');assert.equal(correction.user_feedback.verified,false);
  const reason=await ask(page,'通信异常为什么排在首位？');
  assert.match(reason.summary,/不能确认通信故障/);
  const multi=await ask(page,'什么是同群证据？；实际发电量是多少？；短信和邮件发送成功了吗？');
  assert.equal(multi.answers.length,3);assert.equal(await page.locator('.agent-message.assistant').last().locator('.agent-question-answer').count(),3);
  assert.equal(multi.answers[1].status,'not_connected');
  checks.push('corrections remain feedback and multi-question answers expose missing data');
  await page.screenshot({path:path.join(output,'fumai-conversation-workbench.png'),animations:'disabled'});
  await page.locator('#agent-workbench [data-agent-action=clear]').click();
  await page.waitForFunction(old=>sessionStorage.getItem('fumai-agent-session')!==old,original.session);
  await page.waitForFunction(()=>document.querySelector('.agent-chat-top>span')?.textContent==='服务在线');
  assert.equal(await page.locator('#agent-workbench .agent-message').count(),0);
  assert.equal(await page.evaluate(()=>localStorage.getItem('fumai-agent-client')),original.client);
  const empty=await ask(page,'刚才是否分析过该设备');assert.equal(empty.history_records.length,0);
  const second=await ask(page,'分析 inv_07 的异常证据');assert.notEqual(second.run_id,first.run_id);
  assert.notEqual(second.conversation_id,first.conversation_id);
  checks.push('new conversation rotates ID, clears context, allows repeated analysis');
  const tab=await context.newPage();tab.on('pageerror',e=>errors.push(e.message));
  await tab.goto(base+'/#agent',{waitUntil:'networkidle'});
  assert.equal(await tab.evaluate(()=>localStorage.getItem('fumai-agent-client')),original.client);
  assert.notEqual(await tab.evaluate(()=>sessionStorage.getItem('fumai-agent-session')),second.conversation_id);
  const all=await ask(tab,'列出之前的设备分析记录');assert.equal(all.history_records.length,2);
  await tab.locator('#agent-workbench [data-agent-action=history]').click();await tab.waitForSelector('#agent-history-dialog[open]');
  assert.ok(await tab.locator('[data-agent-conversation]').count()>=2);
  await tab.locator(`[data-agent-conversation="${first.conversation_id}"]`).click();
  await tab.waitForFunction(id=>sessionStorage.getItem('fumai-agent-session')===id,first.conversation_id);
  assert.ok(await tab.locator('#agent-workbench .agent-message').count()>4);
  await tab.reload({waitUntil:'networkidle'});
  assert.equal(await tab.evaluate(()=>sessionStorage.getItem('fumai-agent-session')),first.conversation_id);
  assert.ok(await tab.locator('#agent-workbench .agent-message').count()>4);
  checks.push('same-browser tabs share private history; historical conversation reload restores context');
  const stranger=await browser.newContext({viewport:{width:1280,height:720},reducedMotion:'reduce'});
  const visitor=await stranger.newPage();await visitor.goto(base+'/#agent',{waitUntil:'networkidle'});
  const none=await ask(visitor,'列出之前的设备分析记录');assert.deepEqual(none.history_records,[]);
  const privateHeaders=await headers(visitor);
  const denied=await visitor.request.post(base+'/agent-api/run',{headers:{...privateHeaders,Origin:base},data:{run_id:first.run_id}});
  assert.equal(denied.status(),400);await stranger.close();
  checks.push('another browser cannot read the first visitor records');
  await tab.setViewportSize({width:390,height:844});await visible(tab,'mobile 390');
  await tab.screenshot({path:path.join(output,'fumai-conversation-mobile.png'),animations:'disabled'});
  await tab.setViewportSize({width:320,height:568});await visible(tab,'mobile 320');
  checks.push('long contextual conversation keeps composer visible on phones');
  assert.deepEqual(errors,[]);
  const result={base,checks,pageErrors:errors};fs.writeFileSync(path.join(output,'fumai-conversation-browser-validation.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
 }finally{await browser.close();}
})().catch(error=>{console.error(error.stack);process.exitCode=1;});
