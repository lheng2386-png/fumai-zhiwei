const {chromium} = require(process.env.FUMAI_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const base = process.env.FUMAI_CHECK_URL || 'http://127.0.0.1:4209';
const out = process.env.FUMAI_TEST_OUTPUT || path.resolve('outputs');

(async () => {
    const browser = await chromium.launch({headless: true, ...(process.env.FUMAI_BROWSER_EXECUTABLE ? {executablePath: process.env.FUMAI_BROWSER_EXECUTABLE} : {}), args: ['--enable-unsafe-swiftshader']});
    const context = await browser.newContext({viewport: {width: 1600, height: 1000}, reducedMotion: 'reduce'});
    const page = await context.newPage(), checks = [], errors = [];
    fs.mkdirSync(out, {recursive: true});
    try {
        assert.equal(new URL(base).hostname, '127.0.0.1', 'This fixture mocks only localhost authentication');
        await page.route('**/api/auth/me', r => r.fulfill({contentType: 'application/json', body: JSON.stringify({user: {username: 'daylight_local', display_name: '本地测试', role: 'viewer'}})}));
        page.on('pageerror', e => errors.push(e.message));
        page.on('console', e => { if (e.type() === 'error' && /Shader|WebGLProgram|GL_INVALID/.test(e.text())) errors.push(e.text()); });
        const stats = () => page.evaluate(() => window.FumaiScene.diagnostics());
        const setTime = value => page.locator('[data-sun-range]').evaluate((el, value) => { el.value = value; el.dispatchEvent(new Event('input', {bubbles: true})); }, value);
        await page.goto(base + '/#scene');
        await page.waitForFunction(() => document.querySelector('#scene-workbench')?.dataset.sceneReady === 'webgl');
        assert.equal((await stats()).daylight.playing, false);
        assert.equal((await stats()).daylight.minute, 720);
        assert.match(await page.locator('.scene-daylight').innerText(), /示意太阳轨迹，非现场气象/);
        checks.push('default daylight is paused and its illustrative source is visible');

        const evidence = await page.locator('.scene-selection').innerText();
        const panels = await page.locator('[data-count-panel]').innerText();
        await page.locator('[data-scene-fullscreen]').click();
        await page.waitForFunction(() => window.FumaiScene.diagnostics().expanded);
        await setTime(420); await page.waitForTimeout(150);
        const morning = await stats();
        const am = await page.locator('.scene-viewport canvas').screenshot();
        await page.screenshot({path: path.join(out, 'scene-daylight-morning.png')});
        await setTime(1020); await page.waitForTimeout(150);
        const evening = await stats();
        const pm = await page.locator('.scene-viewport canvas').screenshot();
        assert.ok(morning.daylight.lightPosition[0] > 0 && evening.daylight.lightPosition[0] < 0);
        assert.notEqual(crypto.createHash('sha256').update(am).digest('hex'), crypto.createHash('sha256').update(pm).digest('hex'));
        assert.equal(await page.locator('[data-sun-time]').innerText(), '17:00');
        await page.screenshot({path: path.join(out, 'scene-daylight-evening.png')});
        checks.push('timeline moves actual directional light east to west and changes rendered pixels');
        assert.equal(await page.locator('.scene-selection').innerText(), evidence);
        assert.equal(await page.locator('[data-count-panel]').innerText(), panels);
        checks.push('lighting leaves device measurements and evidence unchanged');

        await page.locator('[data-scene-light]').selectOption('day');
        assert.equal((await stats()).daylight.minute, 720);
        await page.locator('[data-scene-light]').selectOption('dusk');
        assert.equal((await stats()).daylight.minute, 1020);
        await page.locator('[data-sun-reset]').click();
        assert.equal((await stats()).daylight.minute, 720);
        checks.push('day and dusk presets stay synchronized and reset returns to noon');

        await page.locator('[data-sun-play]').click();
        await page.waitForTimeout(700);
        assert.ok((await stats()).daylight.minute > 725);
        await page.locator('[data-sun-play]').click();
        const paused = await stats(); await page.waitForTimeout(350);
        assert.equal((await stats()).daylight.minute, paused.daylight.minute);
        assert.ok((await stats()).frames - paused.frames <= 2);
        checks.push('playback advances and pause stops both time and idle rendering');
        await setTime(1075); await page.locator('[data-sun-play]').click();
        await page.waitForFunction(() => !window.FumaiScene.diagnostics().daylight.playing);
        assert.equal((await stats()).daylight.minute, 1080);
        await page.locator('[data-sun-play]').click(); await page.waitForTimeout(180);
        assert.ok((await stats()).daylight.minute < 370);
        checks.push('playback ends at dusk and explicit replay starts at dawn');
        await setTime(600);
        assert.equal((await stats()).daylight.playing, false);
        await page.locator('[data-sun-play]').click();
        await page.evaluate(() => window.dispatchEvent(new Event('blur')));
        assert.equal((await stats()).daylight.playing, false);
        await page.locator('[data-sun-play]').click();
        await page.evaluate(() => { Object.defineProperty(document, 'hidden', {value: true, configurable: true}); document.dispatchEvent(new Event('visibilitychange')); });
        assert.equal((await stats()).daylight.playing, false);
        await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')); });
        await page.locator('[data-sun-play]').click();
        await page.evaluate(() => document.querySelector('.scene-viewport').style.display = 'none');
        await page.waitForFunction(() => !window.FumaiScene.diagnostics().daylight.playing);
        await page.evaluate(() => document.querySelector('.scene-viewport').style.display = '');
        checks.push('scrubbing, blur, background and offscreen canvas pause playback');

        await page.locator('[data-camera=free]').click();
        await page.locator('[data-sun-play]').click();
        await page.locator('.scene-viewport canvas').focus();
        const before = (await stats()).navigation.position;
        await page.keyboard.down('KeyW'); await page.waitForTimeout(300); await page.keyboard.up('KeyW');
        const after = (await stats()).navigation.position;
        assert.ok(Math.hypot(...after.map((v, i) => v - before[i])) > .2);
        assert.equal((await stats()).daylight.playing, true);
        await page.locator('[data-sun-play]').click();
        checks.push('fullscreen roaming and daylight playback work together');

        await page.setViewportSize({width: 390, height: 844});
        if (await page.locator('[data-scene-panel]').getAttribute('aria-expanded') === 'true') await page.locator('[data-scene-panel]').click();
        await page.locator('[data-sun-reset]').click();
        const mobile = await page.locator('.scene-daylight').boundingBox();
        const canvas = await page.locator('.scene-viewport').boundingBox();
        assert.ok(mobile.y >= canvas.y + canvas.height - 1 && mobile.y + mobile.height <= 844);
        assert.ok(canvas.height >= 300);
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
        await page.screenshot({path: path.join(out, 'scene-daylight-mobile.png')});
        await page.setViewportSize({width: 844, height: 390});
        assert.ok((await page.locator('.scene-viewport').boundingBox()).height >= 150);
        checks.push('portrait and landscape fullscreen keep the timeline separate from the canvas');

        await page.locator('[data-sun-play]').click();
        await page.evaluate(() => window.daylightDisposedHost = document.querySelector('#scene-workbench'));
        await page.evaluate(() => location.hash = 'overview');
        await page.waitForSelector('#main[data-view=overview]');
        assert.equal((await stats()).active, false);
        assert.equal(await page.evaluate(() => window.daylightDisposedHost.dataset.sceneDisposed), 'true');
        checks.push('route exit disposes the running timeline');
        assert.deepEqual(errors, []);
        const result = {base, checks, pageErrors: errors};
        fs.writeFileSync(path.join(out, 'scene-daylight-validation.json'), JSON.stringify(result, null, 2));
        console.log(JSON.stringify(result));
    } finally { await browser.close(); }
})().catch(e => { console.error(e.stack); process.exitCode = 1; });
