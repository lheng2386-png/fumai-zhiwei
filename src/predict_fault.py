"""CSV inference for the locally trained Costa2020 DC-side classifier."""
from pathlib import Path
import argparse,json
import numpy as np
import pandas as pd
import joblib

def predict(input_csv,model_path,output_csv):
 bundle=joblib.load(model_path)  # Only load models generated by this project.
 d=pd.read_csv(input_csv);cols=bundle['features']
 missing=set(cols)-set(d)
 if missing:raise ValueError(f'Missing columns: {sorted(missing)}')
 x=d[cols].apply(pd.to_numeric,errors='coerce')
 if not np.isfinite(x.to_numpy()).all():raise ValueError('Inputs contain missing, non-numeric or non-finite values')
 probabilities=bundle['model'].predict_proba(x)
 classes=bundle['model'].classes_;p=classes[probabilities.argmax(axis=1)]
 out=d.copy();out['predicted_label']=p;out['predicted_name']=[bundle['labels'][int(i)] for i in p];out['model_score']=probabilities.max(axis=1)
 out['review_status']=np.where(out.model_score<.6,'low_score_review','unvalidated_for_other_plants')
 out.to_csv(output_csv,index=False)
 return len(out)
if __name__=='__main__':
 root=Path(__file__).resolve().parents[1]
 a=argparse.ArgumentParser();a.add_argument('input',type=Path);a.add_argument('--model',type=Path,default=root/'models/dc_fault_classifier.joblib');a.add_argument('--output',type=Path,required=True);p=a.parse_args()
 print(json.dumps({'rows':predict(p.input,p.model,p.output),'output':str(p.output)},ensure_ascii=False))
