"""Explicit recovery of the interrupted 960 branch; never rerun completed 640.

Use only checkpoints generated by this project: Ultralytics optimizer/model
checkpoints require trusted local pickle loading. Dry-run unless --execute.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import time
from finetune_pv_hsd_resolution import training_controls,write_json
from train_pv_hsd_tiled_yolo import validate_data


def recovery_action(checkpoint, csv_epoch, expected):
    if not 1<=csv_epoch<=expected['epochs']:raise ValueError('Unexpected completed epoch count')
    for key,value in expected.items():
        if checkpoint.get('train_args',{}).get(key)!=value:
            raise ValueError(f'Resume training control mismatch: {key}')
    epoch=checkpoint.get('epoch')
    if csv_epoch==expected['epochs']:
        if epoch not in (-1,csv_epoch-1):raise ValueError('Final epoch/checkpoint mismatch')
        return 'evaluate_only'
    if epoch!=csv_epoch-1 or checkpoint.get('optimizer') is None:
        raise ValueError('Cannot resume without matching optimizer and epoch')
    return 'resume_training'


def run(args):
    import torch
    import ultralytics
    root=args.output
    protocol_path=root/'protocol.json';report=json.loads(protocol_path.read_text())
    if report['status']=='complete':raise ValueError('Already complete; no recovery needed')
    manifest=validate_data(args.source,args.tiles)
    if (manifest['source_manifest_sha256']!=report['source_manifest_sha256']
            or hashlib.sha256((args.tiles/'manifest.json').read_bytes()).hexdigest()!=report['tile_manifest_sha256']
            or hashlib.sha256(args.checkpoint.read_bytes()).hexdigest()!=report['checkpoint_sha256']
            or torch.__version__!=report['torch_version'] or ultralytics.__version__!=report['ultralytics_version']):
        raise ValueError('Source data/initialization/runtime changed')
    prior=root/'imgsz640';branch=root/'imgsz960'
    if report['branches'].get('imgsz640',{}).get('status')!='complete':raise ValueError('640 branch not complete')
    if hashlib.sha256((prior/'weights/best.pt').read_bytes()).hexdigest()!=report['branches']['imgsz640']['best_sha256']:
        raise ValueError('640 checkpoint changed')
    for size in (640,960):
        cache=json.loads((prior/f'eval{size}_predictions.json').read_text())
        summary=json.loads((prior/f'eval{size}_summary.json').read_text())
        if cache['checkpoint_sha256']!=report['branches']['imgsz640']['best_sha256'] or summary['imgsz']!=size:
            raise ValueError('Completed 640 evaluation inconsistent')
    expected=report['controls']['960']
    if expected!=training_controls(960,expected['epochs'],expected['seed']):raise ValueError('Unknown training recipe')
    rows=list(csv.DictReader((branch/'results.csv').open()))
    csv_epoch=int(rows[-1]['epoch'])
    last=branch/'weights/last.pt'
    checkpoint=torch.load(last,map_location='cpu',weights_only=False)
    action=recovery_action(checkpoint,csv_epoch,expected)
    event={'action':action,'completed_epochs':csv_epoch,
           'last_sha256':hashlib.sha256(last.read_bytes()).hexdigest()}
    print(json.dumps(event),flush=True)
    if not args.execute:return event
    if not torch.cuda.is_available():raise RuntimeError('CUDA unavailable')
    started=time.monotonic()
    report.setdefault('recovery_events',[]).append(event)
    report['status']='recovering';write_json(protocol_path,report)
    if action=='resume_training':
        from ultralytics import YOLO
        model=YOLO(str(last));model.train(resume=True,device=0,workers=expected['workers'])
        del model;torch.cuda.empty_cache()
    best=branch/'weights/best.pt';best_hash=hashlib.sha256(best.read_bytes()).hexdigest()
    report['branches']['imgsz960']={'status':'evaluating','best_sha256':best_hash};write_json(protocol_path,report)
    from evaluate_pv_hsd_tiled import run as evaluate
    for size in (640,960):
        summary=branch/f'eval{size}_summary.json';cache=branch/f'eval{size}_predictions.json'
        if summary.exists() or cache.exists():
            if not summary.exists() or not cache.exists():raise ValueError('Partial evaluation; preserve and audit explicitly')
            saved=json.loads(cache.read_text())
            if saved['checkpoint_sha256']!=best_hash or saved['imgsz']!=size:raise ValueError('Incompatible prior evaluation')
        else:
            evaluate(args.source,best,summary,'cuda',size,4,.001,.5,'tiled',cache)
    report['branches']['imgsz960']['status']='complete';report['status']='complete'
    event['recovery_elapsed_seconds']=time.monotonic()-started
    write_json(protocol_path,report)

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--source',type=Path,default=Path('data/processed/pv_hsd_grouped_v2'))
    p.add_argument('--tiles',type=Path,default=Path('data/processed/pv_hsd_tiles_384_v1'))
    p.add_argument('--checkpoint',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--execute',action='store_true')
    run(p.parse_args())
